/**
 * app.js — 归山记（独立小程序）的启动层
 * ============================================================================
 *
 * 这个文件**故意做得很薄**。
 *
 * 为什么
 * ------
 * 归山记是**独立产品**，不再是 1in8b 小程序里的一个玩法入口 ⇒
 * 它不需要那一整套「先等引擎起来再放行」的流程：
 *
 *   · 不加载 1in8b 引擎；
 *   · 没有 `engineReady` 屏障（首页不需要等任何东西就能显示）；
 *   · 不放背景音乐（修仙这套玩法本来就没有声音）；
 *   · 不联网（完全单机，存档只写 `xianxia.v1.*`）。
 *
 * ⇒ 启动层只负责：告诉微信「我是个小程序」+ 放一点全局常量。
 *   真正的逻辑都在 `subpkg/xianxia/` 里（规则由
 *   `scripts/build-xianxia-mp.mjs` 从本仓库源码生成）。
 *
 * ⚠ 这里的 `globalData` 不要放会变的东西（当前人生、存档句柄）——
 *   那些由 `subpkg/xianxia/bridge/session.js` 管，页面之间靠它接力。
 */
App({
  globalData: {
    /** 产品名（界面上的标题以 app.json 的 navigationBarTitleText 为准）。 */
    appName: '归山记',
    /** 存档命名空间：所有存档键都以它开头（见 bridge/storage.js）。 */
    storageNamespace: 'xianxia.v1.',
  },

  onLaunch: function () {
    /* 完全单机：这里不做任何网络请求、不读任何官方键、不碰任何别的存档。 */
  },
});
