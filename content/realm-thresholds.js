/**
 * 境界门槛 —— 每一境要攒够多少修为、完整心法要练够多少月。
 * ============================================================================
 *
 * ## 为什么这几张表不住在节奏域
 * --------------------------
 * 2026-11-07 之前，它们住在 `content/cadence-table.js`（节奏域）。
 * 但**因果域**也要用它们：
 *   · `packages/adventure/progression.js`（因果域）要判断「什么时候开始备主药」
 *     —— 那道门就是这一境的修为门槛；
 *   · 同一处还要判断「完整心法练够了没有」才让玩家封门冲关。
 *
 * 而域的依赖方向是单向直线：**节奏(④) → 因果(③) → 角色(②) → 世界(①)**
 * ⇒ 因果域**不许**反过来依赖节奏域（`scripts/check-boundaries.mjs` 盯着这条，
 *   而且「新的越界不许再登记许可证」⇒ 只能改结构，不能加豁免）。
 *
 * ⇒ 所以这几张表挪到**角色域**：「每一境要多少修为」本来就是境界体系自己的属性
 *   （角色域＝「人是谁、能走多远」，本来就管境界与寿元）；
 *   节奏域管的是「**什么时候**发突破卡、几岁该到、怎么调度」。
 *
 * ## 三张表
 * ---------
 *   · `REQUIRED_PROGRESS` —— 每一境要攒够的修行进度（进度条画的就是它）；
 *   · `METHOD_MONTHS`     —— 完整心法要练够多少个月才准冲关（0 = 这一级不限）；
 *   · `MATERIAL_TIERS`    —— 哪几境要先备主药才准冲关。
 *
 * ⚠ 本文件进小程序包 ⇒ **不写 `?.` / `??`**（微信转译会改变作用域边界）。
 */

/**
 * 修为门槛 —— 进入这一境要攒够多少「修行进度」。
 *
 * ## 这些数字是**量出来的**，不是拍出来的
 * --------------------------------------
 * 2026-11-07 实测（`scripts/audit-metrics.mjs`，120 条命，默认以修行/学习为主）：
 * 修行进度的实际速度约 **每年 7 点**（灵根、体质、功法、宗门供给都算数，人与人差很多）。
 * 于是门槛定多少 ⇒ 突破年龄落在哪一年，是可以算出来的：
 *
 * | 门槛 | 达到时的岁数（中位） | 对照窗口 |
 * | --- | --- | --- |
 * | 60 | 26 岁 | 筑基 28–42（偏早） |
 * | **120** | **35 岁** | **筑基 28–42 ✔** |
 * | 260 | 58 岁 | 筑基 28–42（超窗 16 年 ✗） |
 *
 * ⇒ 门槛取 120。⚠ 别再随手写 260：那是上游 1in8b 用它自己那套进度速率定的数，
 * 我们的进度速率不同 ⇒ 照抄会让所有人在 58 岁才筑基（这正是 2026-11-07 修掉的病：
 * 「进度条满了却几十年不出突破提示」的另一半根因）。
 *
 * ## 门槛与窗口的关系
 * ------------------
 * · 门槛 = **修为够了没有**（进度条就是它 ⇒ 满了就发卡，不看岁数）；
 * · 窗口（`content/cadence-table.js` 的 `CADENCE`）= **典型年龄**（参考值，不是门槛）
 *   ⇒ 岁数不再拦人，只在过了上界时催一把；
 * · 材料与功法 = **发卡前置**（见 `MATERIAL_TIERS` / `METHOD_MONTHS`）。
 *
 * 这与修仙小说的通行做法一致：突破看的是「积累 + 丹药 + 功法」，没有「到岁数才能突破」这回事。
 */
export const REQUIRED_PROGRESS = {
  /* 炼气：48 点（2026-11-08 · 章节感补强 A1 定档）。
   * ⚠ 旧值 18 配「未入门也攒进度」时，中位 19–21 岁就首突破，太仓促。
   *   A1-b（进度从拿到心法起算，cultivation.js）+ 48 点之后实测（160 命，跑 scripts/play-cultivation）：
   *   首突破中位 24 岁、P10 19、P90 25 —— 快根骨者约 19–20 岁自然攒够，
   *   其余人 20 岁领修行指导卡、闭关 48 个月、24 岁出关冲关（story-rules12 的 r12_direction_0）。
   *   窗口（cadence-table 的 CADENCE）上界随之取 P90 + 2 = 27。 */
  1: 48,
  2: 120,  /* 筑基：攒够这些修为，闭关门一开就能冲（窗口 28–42，中位 35 岁） */
  3: 220,  /* 金丹：材料与功法另算（窗口 95–150） */
  4: 320,  /* 元婴：材料与功法另算（窗口 200–290） */
};

/**
 * 完整心法 —— 要练够多少个月才准冲关。
 *
 * 只对结丹与育婴有要求：炼气与筑基靠的是「积累 + 灵石买料 + 一枚护脉药」，
 * 高阶要「完整法门」（小说里结丹要的是功法与机缘，不是打坐时长）。
 */
export const METHOD_MONTHS = {
  3: 120,
  4: 240,
};

/**
 * 哪几境要先备主药才准冲关（主药清单由 `packages/adventure/progression.js` 的
 * `materialSlots` 按当前状态给 ⇒ 这里只说「哪一境要」）。
 */
export const MATERIAL_TIERS = [3, 4];

/**
 * 某一境的突破门槛。
 * @param {number} realm 境界序号
 * @returns {number} 需要攒够的修行进度
 */
export function progressNeeded(realm) {
  return REQUIRED_PROGRESS[realm] === undefined ? 0 : REQUIRED_PROGRESS[realm];
}
