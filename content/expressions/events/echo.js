/**
 * 表达域 · 修仙线 · 回响（旧识 / 铜匣 / 恩师）（echo 分片，17 张）
 * ============================================================================
 *
 * 这一片是「旧事回响」那条线：当年一起捡柴的伙伴（friend）、家里那只铜匣（relic）、
 * 童年教你认药的人（teacher）。每条线都是三段：收到消息（echo_*）、
 * 回信说清地方（echo_*_check）、真的见一面（echo_*_visit），
 * 外加「旧册里的地址还没用过」（echo_resume）与「战后重新翻开旧信」。
 *
 * ## 改写口径
 * ------------
 *   · **只换说法，不换事实**：数字、期限、代价、后果、人名地名物件名一个都不动。
 *   · **正文一句一件事**：一句话只讲一件事，逗号断句；正文只讲场景，
 *     「要多久」「会怎样」这类条款挪到选项提示语。
 *   · **提示语三段式**：做什么 + 后果一句白话。
 *   · 正文 ≤ 90 字（门禁 `scripts/verify-event-expressions.mjs` 守着）。
 *
 * ## 这一片的三处特别
 * --------------------
 *   1. **不许 import** —— 表达域是数据层，不许反向依赖规则层。
 *      人名、旧事标记、师承、俗世身份全部从 `s` 上自己读。
 *   2. **不许 ES2020 的可选项与空值合并语法** —— 微信小程序端是 ES2019。
 *   3. **三条线各是一张自己的卡** —— 规则层就把 friend / relic / teacher
 *      分开写的，所以这里也分开写；「重新安排」那几张是同一张卡再发一次，
 *      正文照抄那张卡。
 *
 * ## 两处容易写错的状态
 * ----------------------
 *   · **旧识的名字**：`s.life.cultivation.progression.names['阿宁'] || '阿宁'`
 *     —— 玩家可能给旧识改过名，不许写死。
 *   · **旧事标记**：`s.life.cultivation.network.marks`
 *     —— `sold_page`（铜匣换过粮）、`friend_witness` / `friend_hide`（当年那件事
 *     怎么收的场）、`herbs` / `teacher_notes` / `teacher_route`（授业者的线索）。
 */
