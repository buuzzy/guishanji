/**
 * 接头卡 —— 「一条线走完」与「下一件事发生」之间的那张桥
 * ============================================================================
 *
 * ## 为什么要有这个文件
 * ----------------------
 * 实测（60 条命 / 2016 次抉择 / 固定种子）：
 *   · 一条线的三步在抉择序列里**紧挨着**的比例是 **89%** ⇒ 线本身没坏；
 *   · 线走完之后紧接的那张卡**不属于任何线**的比例是 **71%** ⇒ 断点只在一处；
 *   · 全局只有 **21.5%** 的抉择落在某条线上。
 *
 * ⇒ 结论：**线内部是连的，断的是线与线之间。**
 * ⇒ 所以整套改造只加一样新东西：**接头卡** —— 一条线走完的那一刻发的一张卡，
 *   它承接那件事、写下一个旗标、并引出下一件事。
 *
 * ## 三张卡 = 三种收尾
 * ------------------
 * 每条线第三步有三个选项，接头卡按收尾分三张：
 *   · `settled` —— 线是**照规矩来**收的尾（第三步选了 `care`）；
 *   · `pending` —— 线是**留退路**收的尾（第三步选了 `cautious`）；
 *   · `hidden`  —— 线是**只顾自己**收的尾（第三步选了 `selfish`）。
 *
 * ## 命名的两条硬规矩
 * ------------------
 *   ① **卡 id 必须以线 id 开头**：`<线id>_joint_<settled|pending|hidden>`。
 *      `packages/adventure/gates.js` 的 `isMilestone()` 认 `<chainId>_` 前缀
 *      ⇒ 接头卡自动豁免密度闸与冷却闸。
 *      **写成 `joint_sect_repair_open` 就会被密度闸拦掉（十年五张）⇒ 接头卡发不出来。**
 *   ② **旗标名 = `<线id><Open|Hold|Take>`（驼峰，不许下划线）**，写在 `state.flags` 上。
 *      ⚠⚠ **不许用下划线**：`packages/adventure/engine.js` 的存档校验
 *      （`validateRun`）要求旗标名匹配 `/^[a-zA-Z][a-zA-Z0-9]{0,50}$/` ——
 *      带下划线 ⇒ **每次存档都被判无效**（玩家存不进去）、`review()` 直接抛错。
 *      ⇒ 线下划线在**卡 id** 里可以有（卡 id 不是旗标名），旗标名里不行。
 *      这三个名字与卡 id 里的三个词**不是一回事**：
 *        · 卡 id 的 `settled/pending/hidden` 说的是**线怎么收的尾**；
 *        · 旗标的 `open/hold/take` 说的是**你在接头处做了什么**。
 *
 * ## 写回的方向：开路 / 关路，不是扣数值
 * ---------------------------------------
 * 一局一命不能重来 ⇒ 惩罚式后果会让玩家保守、反而更千篇一律。
 * ⇒ 接头卡只写旗标；旗标由**下一拍**那一张卡的某个选项读，
 *   读到的效果是「这个选项对你开放 / 关着，理由是什么」。
 *
 * ## 只对当前版本（规则十二）生效
 * ------------------------------
 * 九个历史事件表快照在 `content/cultivation-stories.js` 中间就拍好了；
 * 本文件的安装器在**快照之后**才被调用 ⇒ 旧档一个字节都不动
 * （门禁 `scripts/verify-events-fidelity.mjs` 盯着）。
 */

