/**
 * 「人生场景」旁白池 —— **当时正在发生**的那一类。
 * ============================================================================
 *
 * ## 为什么要有这一池（2026-11-08 · 阶段 5）
 * ------------------------------------------------
 * 官方的节奏是「一件大事 + 六件小事」：**每弹 1 张决策卡，平均伴随 6.5 条人生经历**
 * （官方对照报告 §6.2：一生流水中位 362 条 ÷ 一生决策卡中位 56 张 = 6.5:1）。
 *
 * 我们这边同口径只有 **3.99:1**（一生流水中位 155 ÷ 决策卡中位 41）⇒ 血不够肉。
 *
 * ⚠ **原有的池子全是「事后交代」** ——
 *   「多年以后你回想起…」「若干年后…」，写的是**已经过去的事**。
 *   玩家读的时候，眼前的年月是空的：没有「今天你在做什么」。
 * ⇒ 这一池补的正是**当时正在发生**：今天你在哪、手上在忙什么、身边出了什么事。
 *
 * ## 这一池与原有池子的分工
 * ----------------------
 * | 池子 | 写什么 | 多久一条 | 排期 |
 * | --- | --- | --- | --- |
 * | 原有池（`cultivation-daily.js`） | 事后交代、拾遗、印记后果 | 24–48 个月（且常常白吃名额） | `c.dailyAt`（规则层排期） |
 * | **本池** | **当时正在发生的场景** | 20–60 个月（按人生阶段） | **种子哈希**（见下） |
 *
 * ## ⚠⚠ 排期为什么用哈希、而不是随机流
 * ------------------------------------
 * 规则层的 `delay()` 从 **`events` 流**抽签，而 `events` 流同时决定
 * 「这一批候选卡里发哪一张」（`packages/adventure/cultivation.js` 的
 * `allowed[Math.floor(random(s,'events')*allowed.length)]`）。
 * ⇒ **旁白节奏一旦改动，抽签次数就会变 ⇒ 整条决策序列跟着变。**
 *
 * 本池的排期与挑行**一律用 `hashText`（种子哈希）**：
 *   · 不碰任何随机流 ⇒ **决策序列一个字节都不变**（`eventseq` 门禁保持绿）；
 *   · 同一条命、同一颗种子 ⇒ 排期与挑行永远一样（可复现）；
 *   · 以后再调旁白密度 ⇒ **只改内容与间隔，不动卡牌抽签**。
 *
 * ## 挑行规矩
 * ----------
 * · 同一组里，**用过的行不再用第二次**，直到这一组用完（记在 `c.dailyMemory`）；
 * · 用完了就不再从这一组取（不循环重复）⇒ 宁可少一条，也不给玩家看两遍同一句；
 * · 冷却闸（60 个月同标题）由规则层的 `titleAllows` 统一管着，两条通道共用一份口径。
 *
 * ## 池子规模
 * ----------
 * 每组 ≤ 64 行 —— 存档校验（`validateCultivation` 的「日常故事记忆」）
 * 要求记忆数组长度 ≤ 64、元素 ≤ 64 ⇒ **每组行数不能超过 64**。
 */

