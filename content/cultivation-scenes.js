/**
 * 人生阶段 —— 决定这一条场景从哪一组里取。
 *
 * ⚠ 年龄算的是**在这个世界里的岁数**（`s.birth.startAge` 也要算进去）。
 * @param {object} s 当前人生状态
 * @returns {string} 组名
 */
export function sceneGroup(s, context) {
  /* 路上一段与思过期间：原有池子已经讲（`rows.travel` / `rows.explore` / `rows.confinement`）
     ⇒ 这一池不叠着说（同一件事写两遍，比不写更糟）。 */
  if (context === 'travel' || context === 'valley' || context === 'cavern' || context === 'outer' || context === 'confinement') return null;
  if (context === 'retreat') return 'retreat';       /* 闭关期间另有一组 */
  const years = Math.floor(s.month / 12) + (s.birth.startAge || 0);
  if (years < 16) return 'childhood';
  if (years < 25) return 'entry';
  if (years < 60) return 'sect';
  return 'later';
}

/**
 * 这一条场景的间隔与相位 —— **种子哈希，不占随机流**。
 *
 * ⚠ 间隔随人生阶段变长：年轻时的日子过得快、变化多，
 *   越到后面一年与一年之间越像 ⇒ 间隔从 12 个月一路拉长到 40 多个月。
 *
 * @param {object} s 当前人生状态
 * @param {string} group 组名
 * @returns {{period:number, anchor:number, base:number}} 间隔（月）、相位（月）、起始序号
 */
export function sceneCadence(s, group) {
  const span = {childhood: 12, entry: 12, sect: 15, retreat: 60, later: 21}[group] || 20;
  const period = span + hashText(String(s.seed) + ':场景间隔:' + group) % 8;
  const anchor = hashText(String(s.seed) + ':场景相位:' + group) % period;
  const base = hashText(String(s.seed) + ':场景起点:' + group);
  return {period, anchor, base};
}

/**
 * 这个月是不是「该讲一条场景」。
 *
 * ⚠ 纯函数：同一条命、同一个月份，答案永远一样。
 * @param {object} s 当前人生状态
 * @param {string} context 当前情境
 * @returns {boolean} 该讲就讲
 */
export function sceneDue(s, context) {
  if (s.month < 12) return false;                 /* 一岁以前不讲 */
  const group = sceneGroup(s, context);
  if (!group) return false;
  const {period, anchor} = sceneCadence(s, group);
  return (((s.month - anchor) % period) + period) % period === 0;
}

/**
 * 挑一条场景 —— **顺序走池**。
 *
 * ## 为什么不是「抽签 + 记着用过」
 * -----------------------------
 * 「用过的行不再用第二次」这种做法要记账（`c.dailyMemory`），
 * 而存档校验要求每个键的记忆数组 ≤ 64 ⇒ **每组最多 64 行**。
 * 可一条命能走到后期三百年，后期那一组要走上百条 ⇒ 记账的做法必然写空。
 *
 * ## 顺序走池怎么做的
 * ------------------
 * · `slot = (本月 − 相位) ÷ 间隔` —— 这一组的第几拍（只增不减）；
 * · `index = (起始序号 + slot) 对行数取余` ⇒ **一条一条顺着走**。
 * ⇒ 一条行用完一整轮才会再轮到 ⇒ 同一条标题至少隔着一整轮才可能出现
 *   （冷却闸那 60 个月根本不会碰到它），而池子多大都不受限制。
 *
 * ⚠ 换组时 `slot` 继续往上数 ⇒ 同一个组以后再进来，接着上次的位置走。
 *
 * @param {object} s 当前人生状态
 * @param {string} context 当前情境
 * @returns {{title:string, body:string}|null} 这一条场景
 */
export function sceneStory(s, context) {
  const group = sceneGroup(s, context);
  const pool = SCENES[group];
  if (!pool || !pool.length) return null;
  const {period, anchor, base} = sceneCadence(s, group);
  const slot = Math.floor((s.month - anchor) / period);
  const index = (((base + slot * sceneStride(pool.length, group)) % pool.length) + pool.length) % pool.length;
  const row = pool[index];
  return {title: row[0], body: row[1]};
}

/**
 * 走池的步长 —— **必须与池子长度互素**。
 *
 * ⚠ 为什么要互素：
 *   走池是「第 n 拍取第 (起点 + n×步长) 行」。
 *   步长若与池长不互素 ⇒ 只能走到池子的一部分（其余那些行**永远轮不到**，
 *   看着像写了很多、其实发霉）。
 *   互素 ⇒ 走满「池长」拍必定把每一行都走到一遍。
 *
 * @param {number} length 池子行数
 * @param {string} group 组名
 * @returns {number} 步长
 */
export function sceneStride(length, group) {
  if (length < 2) return 1;
  for (let step = 1 + hashText(String(group) + ':步长') % (length - 1); step < length; step++) {
    if (gcd(step, length) === 1) return step;
  }
  return 1;
}

/** 最大公约数（步长要与池长互素）。 */
function gcd(a, b) {
  let x = a, y = b;
  while (y) { const t = y; y = x % y; x = t; }
  return x;
}
