 /* 行囊里已有的那件就跳过，往后顺延 —— 不然抽到重复的就白抽一次。 */
 for(let i=0;i<pool.length;i++){const row=pool[(which+i)%pool.length];if(row&&!s.inventory.includes(row[2]))return row;}
