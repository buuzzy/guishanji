/**
 * md.js —— 文案里的 `**强调**` 变成真的加粗
 * ============================================================================
 *
 * ## 为什么要有这个
 * ------------------
 * 面板的提示文字里大量用 `**这样**` 来强调（写文档的习惯）。
 * 但面板**不是 markdown 渲染器** ⇒ 那些星号会原样印在页面上，
 * 看起来像出错了（`只是**这批命**没走到`）。
 *
 * ⇒ 这里把 `**xxx**` 换成 `<b>xxx</b>`，其余照旧转义。
 *
 * ## ⚠ 口径
 * --------
 * 只认成对的 `**`；不解析其它 markdown（标题 / 列表 / 链接）——
 *   面板的文案是自己写的，不需要一个 markdown 引擎。
 *   ⚠ 先转义再替换 ⇒ 文案里的 `<` `&` 不会被当成标签。
 */

const esc = text => String(text ?? '').replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));

/**
 * 把文案渲染成 HTML（转义 + `**强调**` → 加粗）。
 * @param {string} text 原始文案
 * @returns {string} 可直接放进 innerHTML 的片段
 */
export function md(text) {
  return esc(text).replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
}
