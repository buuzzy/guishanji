/**
 * 旗标名 —— 线 id + 后缀，转成**驼峰**。
 *
 * ⚠⚠ **不许带下划线**（2026-11-08 实测踩到）：
 *   `packages/adventure/engine.js` 的存档校验（`validateRun`）要求旗标名匹配
 *   `/^[a-zA-Z][a-zA-Z0-9]{0,50}$/` ⇒ `sect_repair_take` 这种名字
 *   **每次存档都被判「故事标记内容」无效**（玩家存不进去，`review()` 也抛错）。
 *   ⇒ 下划线只许出现在**卡 id** 里（卡 id 不受这条校验管）。
 *
 * @param {string} chainId 线 id（如 `sect_repair`）
 * @param {string} suffix `open` / `hold` / `take`
 * @returns {string} 旗标名（如 `sectRepairTake`）
 */
export const jointFlag = (chainId, suffix) =>
  chainId.replace(/[_-]+([a-zA-Z0-9])/g, (_, ch) => ch.toUpperCase())
    + suffix.charAt(0).toUpperCase() + suffix.slice(1);

/**
 * 接头卡发出去后等几个月。
 *
 * ⚠⚠ **固定值，不抽随机数**（这是整个改造里最容易踩的坑）：
 *   接线如果走 `choice.next`，引擎会执行 `delay(s,2,6)` ——
 *   那要从 `events` 随机流里抽一次，而**同一条流还决定随机池抽哪张卡**
 *   ⇒ 每条命后面所有不相干的随机卡全变 ⇒ 差异审查淹在噪音里。
 *
 * ⇒ 这里固定 **0**：到期即到，差异里只看得到「多插了一张接头卡」。
 *
 * ## 为什么是 0（不是 3，也不是 6）
 * -------------------------------
 * 桥的意义是「线一走完，接上的那件事马上发生」⇒ 晚三个月，线与线之间就断了。
 *
 * 实测（60 条命，两种玩法并跑）：
 *   · 固定 3 个月 ⇒ 延迟中位 9 个月、最大 **71 个月**（将近 6 年），
 *     超过 12 个月的占 29% ⇒ 桥基本等于没有。
 *   · 逐月追踪找到两个原因：
 *     ① 队列里的卡要等 `journey.open`（玩家手上没有进行中的事）才发
 *        ⇒ 玩家在赶路/闭关时，桥被压住；
 *     ② 留出几个月空档会让**下一条线开起来**，`activeChain` 占住
 *        ⇒ 桥要等那条新线走完（最长 42 个月）。
 *
 * ⇒ 改成 0 之后：
 *   · `longChainDue` 见到队列里有接头卡就**不开新线**（`scheduler.js`）
 *     ⇒ 桥一定先修好，再谈下一条线；
 *   · 玩家在赶路/闭关时，仍旧礼貌地等他空下来（`jointCardMonth` 要 `journey.open`）
 *     ⇒ 桥不会打断进行中的行动。
 */
