/**
 * 凡人线「在用哪几张卡」—— 交接文档 §3.3 的清单
 * ============================================================================
 *
 * ## 这一步做了什么（2026-11-08 · 阶段 3.3）
 * -------------------------------------------
 * 交接文档要求：**凡人线单命触发 ≤ 5 张卡**（实测改前是 12–20 张）。
 *
 * ⇒ 做法：**停用但不删** —— 这 45 张卡的正文、选项、表达域说法**一个字都不改**，
 *   它们仍然在事件表里（门禁、审计、旧档都读得到），只是**不再发出去**。
 *   ⇒ 放回来只要把 `MUNDANE_KEPT` 改回五张即可，**内容一个字都不用重写**。
 *
 * ## 为什么是这五张（选它的理由）
 * --------------------------------
 * 交接文档给的候选是：`m11_start` / `m11_work_2` / (`m11_family_2`|`m11_visitor_1`)
 *                   / (`m11_gift_2`|`m11_corpse_2`) / `m11_end`。
 *
 * ⚠ **候选里有四张不能单独发** —— 它们正文里写的事情，是**前面某张弧卡**做出来的：
 *   · `m11_family_2`（「共同生活留下的打算」）正文要「伴侣已经存在」，
 *     而伴侣是 family 弧**第 1 步**（`m11_family_1`）答「一起过日子」才定下的
 *     ⇒ 单独发它，正文会走「伴侣已经离世」那一支 ⇒ 说了一件玩家没经历过的事；
 *   · `m11_gift_2`（「药液已经备好」）的前提是「药液已备好 + 木牌残页」，
 *     那是 gift 弧第 0/1 步与 corpse 弧的产物 ⇒ 单独发会抛「植灵来源或材料不完整」；
 *   · `m11_corpse_2`（「河滩旧物有了来问的人」）的前提是「河滩尸体已被发现并取物」
 *     ⇒ 单独发读到的是空的 `m.corpse` ⇒ 正文直接崩；
 *   · `m11_visitor_1`（「接引弟子来问那一夜」）的前提是「那一夜」
 *     ⇒ 单独发会说一件玩家没经历过的事。
 *
 * ⇒ 选**自足**的那几张：事件就发生在这张卡上的卡。
 *
 * | 位置 | 卡 | 干什么 |
 * | --- | --- | --- |
 * | 起 | `m11_start` | 落选，选一份凡人能做的活计（外院 / 药铺 / 租田） |
 * | 承 | `m11_work_2` | 几年下来管事要把带新人的差事交给你（立业） |
 * | 转 | `m11_family_1` | 同住熟人问你要不要正式一起过日子（一次意外：家事） |
 * | 合 | `m11_corpse_0` | 河滩上那具修士尸身，取走还是报信（转机与代价） |
 * | 结 | `m11_end` | 工具和旧信，该交给谁（交代后事） |
 *
 * ## 为什么「转」用 `m11_family_1` 而不是文档候选的 `m11_family_2`
 * -----------------------------------------------------------
 * 文档候选的 `m11_family_2` 依赖伴侣先在 ⇒ 伴侣只能由 `m11_family_1` 建立
 * ⇒ **换成 `m11_family_1` 当转卡**，它自己就把「伴侣」这件事说清楚、答完就定下伴侣
 * ⇒ 后面 `m11_end` 才分得出「人间仍有灯火」与「一门手艺，一世风霜」两个结局。
 *
 * ## 停用的代价（老实记下来）
 * --------------------------
 * 停用 ⇒ 凡人线下面这些**不再出现**：
 *   · 迟入道（`m11_gift_*`）与结局「将尽之时，初见灵光」（`mundane_glimmer`）；
 *   · 「未结清的旧账」（`mundane_unpaid`）—— 没有欠账的来源了；
 *   · 「护路纸符」（`mortal_charm`）—— 只在 corpse 弧第 3 步给；
 *   · 12 张 `m11_life_*` 晚年卡 ⇒ 晚年能碰到的卡种数会变少。
 *
 * ⚠ 这些是**有意**的取舍，不是写漏了；门槛线由 `scripts/audit-completeness.mjs`
 *   的缺口台账盯着（门槛数字只住 `scripts/lib/completeness-limits.js` 一份）。
 */

